//******************** Comperison **********************//

// basic
console.log(2>1);
console.log(2>=1);
console.log(2<1);
console.log(2<=1);
console.log(2==1);
console.log(2!=1);

// String 
console.log("2">1);   //true
console.log("02">1);  // true

// NULL
console.log(null > 0);
console.log(null == 0);
console.log(null < 0);
console.log(null >=0);
console.log(null <= 0);

// undefined 
console.log(undefined == 0);
console.log(undefined > 0);
console.log(undefined <= 0);

// === (Strict comparision)
// it's the comparision with data types

console.log("2"== 2)  // true
console.log("2"=== 2) // false